// Build fast lookup maps for emojis and tags
export const SOUND_BY_ID: Record<string, SoundEffectItem> = {};
export const EMOJI_TO_SOUND: Record<string, SoundEffectItem> = {};
export const TAG_TO_SOUND: Record<string, SoundEffectItem> = {};

for (const item of SOUND_CATALOG) {
  SOUND_BY_ID[item.id] = item;
  for (const emoji of item.emojis) {
    const clean = emoji.replace(/\uFE0F/g, '');
    if (!EMOJI_TO_SOUND[emoji]) EMOJI_TO_SOUND[emoji] = item;
    if (!EMOJI_TO_SOUND[clean]) EMOJI_TO_SOUND[clean] = item;
  }
  for (const tag of item.tags) {
    TAG_TO_SOUND[tag.toLowerCase().trim()] = item;
  }
}

