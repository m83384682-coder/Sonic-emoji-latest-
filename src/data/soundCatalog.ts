/**
 * Resolves ANY Unicode emoji to a SoundEffectItem, even if not explicitly listed,
 * by inspecting its Unicode code point block so that 100% of emojis produce a sound effect!
 */
export function resolveEmojiToSound(rawEmoji: string): SoundEffectItem {
  const trimmed = rawEmoji.trim();
  const stripped = trimmed.replace(/\uFE0F/g, '');
  if (EMOJI_TO_SOUND[trimmed]) return EMOJI_TO_SOUND[trimmed];
  if (EMOJI_TO_SOUND[stripped]) return EMOJI_TO_SOUND[stripped];

  for (const char of Array.from(stripped)) {
    if (EMOJI_TO_SOUND[char]) return EMOJI_TO_SOUND[char];
  }

  const cp = trimmed.codePointAt(0) || 0;

  // Smileys & Emotion (U+1F600 - U+1F64F)
  if (cp >= 0x1f600 && cp <= 0x1f60f) return SOUND_BY_ID['laugh'];
  if (cp >= 0x1f610 && cp <= 0x1f61f) return SOUND_BY_ID['crickets'];
  if (cp >= 0x1f620 && cp <= 0x1f62f) return SOUND_BY_ID['sad_cry'];
  if (cp >= 0x1f630 && cp <= 0x1f64f) return SOUND_BY_ID['dramatic_suspense'];

  // Supplemental Symbols and Pictographs (U+1F900 - U+1F9FF)
  if (cp >= 0x1f910 && cp <= 0x1f92f) return SOUND_BY_ID['cartoon_boing'];
  if (cp >= 0x1f950 && cp <= 0x1f96f) return SOUND_BY_ID['minecraft_eating'];
  if (cp >= 0x1f970 && cp <= 0x1f97f) return SOUND_BY_ID['party_popper'];
  if (cp >= 0x1f980 && cp <= 0x1f9ae) return SOUND_BY_ID['dog_bark'];
  if (cp >= 0x1f9b0 && cp <= 0x1f9ff) return SOUND_BY_ID['woodblock_knock'];

  // Animals & Nature (U+1F400 - U+1F43F)
  if (cp >= 0x1f400 && cp <= 0x1f43f) return SOUND_BY_ID['songbirds'];

  // People / Hand gestures (U+1F440 - U+1F4FF)
  if (cp >= 0x1f440 && cp <= 0x1f450) return SOUND_BY_ID['applause'];
  if (cp >= 0x1f451 && cp <= 0x1f4ff) return SOUND_BY_ID['wind_chimes'];

  // Food & Drink (U+1F32D - U+1F37F)
  if (cp >= 0x1f32d && cp <= 0x1f374) return SOUND_BY_ID['minecraft_eating'];
  if (cp >= 0x1f375 && cp <= 0x1f37f) return SOUND_BY_ID['drinking_gulp'];

  // Activities, Party, Sports (U+1F380 - U+1F3FF)
  if (cp >= 0x1f380 && cp <= 0x1f39f) return SOUND_BY_ID['party_popper'];
  if (cp >= 0x1f3a0 && cp <= 0x1f3ff) return SOUND_BY_ID['team_cheer'];

  // Transport & Map Symbols (U+1F680 - U+1F6FF)
  if (cp >= 0x1f680 && cp <= 0x1f6ff) return SOUND_BY_ID['race_car'];

  return SOUND_BY_ID['cartoon_boing'];
}

